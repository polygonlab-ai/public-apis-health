<?php

declare(strict_types=1);

namespace PolygonLab\PublicApisHealth\Tools;

/**
 * Page LIST.md, entièrement générée : les entrées regroupées par catégorie, avec leur nom (lié à leur adresse), leur
 * description, la valeur « Auth » déclarée par la liste et le résultat de leur test.
 *
 * Toute valeur venue de la liste est échappée ; seule une adresse http ou https sans caractère douteux devient un
 * lien.
 */
final class ListPage
{
    public const FILE = 'LIST.md';

    /** Adresse qui peut être placée telle quelle dans un lien Markdown, parenthèses encodées à part. */
    private const SAFE_URL = '~\Ahttps?://[^\s<>\[\]|"\'`\\\\]+\z~';

    private const HEADER = "# List of APIs by category\n\n"
        . "> Page generated by `tools/actualiser.php` at each version of the list: do not edit it by hand.\n"
        . "> The list comes from [public-apis/public-apis](https://github.com/public-apis/public-apis) (MIT licence); only the test results are added here.\n"
        . "> What the test measures, and its limits: see the [README](README.md).\n";

    /**
     * @param list<Api> $apis
     */
    public static function render(?string $sourceDate, array $apis): string
    {
        if ($apis === [] || $sourceDate === null) {
            return self::HEADER . "\n_The list will be published here after the first reading of the source._\n";
        }
        /** @var array<string, list<Api>> $groups */
        $groups = [];
        foreach (DataFiles::sorted($apis) as $api) {
            $groups[$api->category][] = $api;
        }

        $lines = [
            self::HEADER,
            sprintf(
                'List read and tested on %s: %s in %s. `Auth` is the value declared by the list; `Test` is the result of the weekly test of the link.',
                $sourceDate,
                Updater::plural(\count($apis), 'API', 'APIs'),
                Updater::plural(\count($groups), 'category', 'categories'),
            ),
        ];
        foreach ($groups as $category => $group) {
            $lines[] = '';
            $lines[] = '## ' . Text::markdown((string) $category) . ' (' . \count($group) . ')';
            $lines[] = '';
            $lines[] = '| API | Description | Auth | Test |';
            $lines[] = '|---|---|---|---|';
            foreach ($group as $api) {
                $lines[] = '| ' . self::name($api) . ' | ' . Text::markdown($api->description ?? '') . ' | ' . Text::markdown($api->auth ?? '') . ' | `' . $api->test . '` |';
            }
        }

        return implode("\n", $lines) . "\n";
    }

    private static function name(Api $api): string
    {
        $name = Text::markdown($api->name);
        if (preg_match(self::SAFE_URL, $api->url) !== 1) {
            return $name;
        }

        return '[' . $name . '](' . str_replace(['(', ')'], ['%28', '%29'], $api->url) . ')';
    }
}
